    function getLang() {
        try {
            return localStorage.getItem(LANG_KEY) === 'en' ? 'en' : 'zh';
        } catch (error) {
            return 'zh';
        }
    }

    function normalize(value) {
        return String(value || '').replace(/\s+/g, ' ').trim();
    }

    function translateChineseSubstrings(text) {
        // Pattern 替换之后，捕获组里可能仍是中文（例如 "3D拉花 · Product List"），
        // 把每段含中文的 token（允许混 ASCII / 数字 / 连字符）再过一遍 TEXT 字典，命中就替换。
        return text.replace(/[A-Za-z0-9一-鿿\-_*·]+/g, chunk => {
            if (!/[一-鿿]/.test(chunk)) return chunk;
            const n = normalize(chunk);
            if (Object.prototype.hasOwnProperty.call(TEXT, n)) return TEXT[n];
            for (let i = 0; i < PATTERNS.length; i += 1) {
                if (PATTERNS[i][0].test(n)) return n.replace(PATTERNS[i][0], PATTERNS[i][1]);
            }
            return chunk;
        });
    }

    function translate(value, lang) {
        const key = normalize(value);
        if (!key) return value;
        if (lang === 'en') {
            if (Object.prototype.hasOwnProperty.call(TEXT, key)) return TEXT[key];
            for (let i = 0; i < PATTERNS.length; i += 1) {
                const pattern = PATTERNS[i][0];
                if (pattern.test(key)) {
                    const replaced = key.replace(pattern, PATTERNS[i][1]);
                    return translateChineseSubstrings(replaced);
                }
            }
            // 兜底：原串没整段命中，也尝试把可识别的中文 token 替掉
            if (/[一-鿿]/.test(key)) {
                const swapped = translateChineseSubstrings(key);
                if (swapped !== key) return swapped;
            }
            return value;
        }
        return value;
    }

    function hasEnglishTranslation(value) {
        const key = normalize(value);
        if (!key) return false;
        if (Object.prototype.hasOwnProperty.call(TEXT, key)) return true;
        if (PATTERNS.some(item => item[0].test(key))) return true;
        // 兜底：如果含中文 token，substring 兜底可能能翻译一部分
        if (/[一-鿿]/.test(key)) {
            return translateChineseSubstrings(key) !== key;
        }
        return false;
    }

    function preserveWhitespace(original, translated) {
        const prefix = String(original).match(/^\s*/)[0];
        const suffix = String(original).match(/\s*$/)[0];
        return `${prefix}${translated}${suffix}`;
    }

    function shouldSkipElement(element) {
        if (!element || element.nodeType !== 1) return false;
        if (SKIP_TAGS.has(element.tagName)) return true;
        if (element.getAttribute && element.getAttribute('data-admin-i18n-ignore') === 'true') return true;
        return false;
    }

    function applyTextNode(node, lang) {
        if (!node || node.nodeType !== 3 || !normalize(node.nodeValue)) return;
        const parent = node.parentElement;
        if (shouldSkipElement(parent)) return;
        if (!node.__adminPageI18nOriginal) node.__adminPageI18nOriginal = node.nodeValue;
        if (getLang() === 'en' && hasEnglishTranslation(node.nodeValue)) {
            node.__adminPageI18nOriginal = node.nodeValue;
        }
        const original = node.__adminPageI18nOriginal;
        const translated = translate(original, lang);
        const nextValue = lang === 'en' ? preserveWhitespace(original, translated) : original;
        if (node.nodeValue !== nextValue) node.nodeValue = nextValue;
    }

    function applyAttributes(element, lang) {
        if (!element || element.nodeType !== 1 || shouldSkipElement(element)) return;
        ATTRS.forEach(attr => {
            const value = element.getAttribute && element.getAttribute(attr);
            if (!value) return;
            if (!element.__adminPageI18nAttrs) element.__adminPageI18nAttrs = {};
            if (!element.__adminPageI18nAttrs[attr]) element.__adminPageI18nAttrs[attr] = value;
            if (getLang() === 'en' && hasEnglishTranslation(value)) {
                element.__adminPageI18nAttrs[attr] = value;
            }
            const original = element.__adminPageI18nAttrs[attr];
            const nextValue = lang === 'en' ? translate(original, lang) : original;
            if (value !== nextValue) element.setAttribute(attr, nextValue);
        });
    }

    function walk(node, visitor) {
        if (!node) return;
        visitor(node);
        if (node.nodeType === 1 && shouldSkipElement(node)) return;
        const children = node.childNodes || [];
        for (let i = 0; i < children.length; i += 1) {
            walk(children[i], visitor);
        }
    }

    function apply(root) {
        const lang = getLang();
        const target = root || document.body || document;
        if (document.title) {
            if (!document.__adminPageI18nTitle) document.__adminPageI18nTitle = document.title;
            document.title = lang === 'en' ? translate(document.__adminPageI18nTitle, lang) : document.__adminPageI18nTitle;
        }
        walk(target, node => {
            if (node.nodeType === 3) applyTextNode(node, lang);
            if (node.nodeType === 1) applyAttributes(node, lang);
        });
    }

    function scheduleApply() {
        if (window.setTimeout) window.setTimeout(() => apply(), 0);
        else apply();
    }

    function scheduleApplySeries() {
        apply();
        if (!window.setTimeout) return;
        [50, 200, 600].forEach(delay => {
            window.setTimeout(() => apply(), delay);
        });
    }

    window.CofeAdminPageI18n = {
        apply,
        getLang,
        translate,
        translations: TEXT
    };

    if (document.addEventListener) {
        document.addEventListener('DOMContentLoaded', () => scheduleApplySeries());
        document.addEventListener('click', event => {
            const target = event.target && event.target.closest ? event.target.closest('[data-admin-lang-option]') : null;
            if (target) scheduleApplySeries();
        }, true);
    }
    if (window.addEventListener) {
        window.addEventListener('load', () => scheduleApplySeries());
        window.addEventListener('storage', event => {
            if (!event || event.key === LANG_KEY) scheduleApplySeries();
        });
    }
    if (typeof MutationObserver !== 'undefined' && document.body) {
        const observer = new MutationObserver(() => scheduleApply());
        observer.observe(document.body, { childList: true, subtree: true });
    }
